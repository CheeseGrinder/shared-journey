package fr.cheesegrinder.sharedjourney.client.render;

import fr.cheesegrinder.sharedjourney.api.SharedJourneyConstants;
import fr.cheesegrinder.sharedjourney.client.config.MinimapClientConfig.FrameTheme;

import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.renderer.GameRenderer;
import net.minecraft.resources.ResourceLocation;

import com.mojang.blaze3d.systems.RenderSystem;
import com.mojang.blaze3d.vertex.BufferBuilder;
import com.mojang.blaze3d.vertex.BufferUploader;
import com.mojang.blaze3d.vertex.DefaultVertexFormat;
import com.mojang.blaze3d.vertex.Tesselator;
import com.mojang.blaze3d.vertex.VertexFormat;
import org.joml.Matrix4f;

import java.util.Locale;

/**
 * Texture-based minimap frame, drawn over the map content. Each theme
 * ({@link FrameTheme}) ships two pre-drawn textures generated by
 * {@code tools/MinimapFrameGenerator.java}:
 *
 * <ul>
 *   <li>{@code <theme>_round.png}, a polar strip (angle x radius) wrapped
 *       around a ring mesh whose radius is the exact on-screen one: the
 *       circle is antialiased by bilinear sampling at any minimap size and
 *       GUI scale, instead of being a fixed-size bitmap resampled;
 *   <li>{@code <theme>_square.png}, a 9-slice without centre authored at
 *       {@value #SLICE_SCALE} texels per GUI pixel: corners keep their size,
 *       the straight edges stretch along the side.
 * </ul>
 *
 * <p>The frame band overlaps the map by {@code inset} GUI pixels (it hides
 * the jagged cut of the circular depth mask) and extends {@code thickness -
 * inset} pixels outside it. The texture sizes and the per-theme numbers
 * below must match the generator.
 */
public final class MinimapFrame {

    /** Texels per GUI pixel in the square textures. */
    private static final int SLICE_SCALE = 4;

    /** Texels of the stretched middle part of each square edge. */
    private static final int MID = 8;

    /** Band geometry of one theme, in GUI pixels. */
    private record Band(float roundThickness, float roundInset, int squareThickness, int squareInset) {}

    private MinimapFrame() {}

    private static Band band(FrameTheme theme) {
        return switch (theme) {
            case CLASSIC -> new Band(3.25f, 1f, 1, 0);
            case STONE, WOOD -> new Band(4f, 1f, 4, 1);
            case THIN -> new Band(2.25f, 1f, 2, 1);
        };
    }

    private static ResourceLocation texture(FrameTheme theme, String shape) {
        return ResourceLocation.fromNamespaceAndPath(
                SharedJourneyConstants.MOD_ID,
                "textures/gui/minimap_frame/" + theme.name().toLowerCase(Locale.ROOT) + "_" + shape + ".png");
    }

    /**
     * Round frame around a circular minimap of radius {@code half} centered
     * on (cx, cy). Call after the depth mask has been reset.
     */
    public static void drawRound(GuiGraphics gg, float cx, float cy, float half, FrameTheme theme) {
        Band band = band(theme);
        float rIn = half - band.roundInset();
        float rOut = rIn + band.roundThickness();
        Matrix4f mat = gg.pose().last().pose();

        // The pending GUI batch must land first to keep the stacking order.
        gg.flush();
        prepare(texture(theme, "round"));
        // Face culling is off: the strip is wound clockwise on screen.
        RenderSystem.disableCull();
        BufferBuilder buf =
                Tesselator.getInstance().begin(VertexFormat.Mode.TRIANGLE_STRIP, DefaultVertexFormat.POSITION_TEX);
        int segments = MinimapRenderer.CIRCLE_SEGMENTS;
        for (int i = 0; i <= segments; i++) {
            float c = MinimapRenderer.CIRCLE_COS[i];
            float s = MinimapRenderer.CIRCLE_SIN[i];
            // u runs a full turn (the texture wraps seamlessly), v the band.
            float u = (float) i / segments;
            buf.addVertex(mat, cx + c * rOut, cy + s * rOut, 0f).setUv(u, 1f);
            buf.addVertex(mat, cx + c * rIn, cy + s * rIn, 0f).setUv(u, 0f);
        }
        BufferUploader.drawWithShader(buf.buildOrThrow());
        RenderSystem.enableCull();
    }

    /** Square frame around the map rectangle (x, y, size x size), in GUI pixels. */
    public static void drawSquare(GuiGraphics gg, int x, int y, int size, FrameTheme theme) {
        Band band = band(theme);
        int t = band.squareThickness();
        int outward = t - band.squareInset();
        float x0 = x - outward;
        float y0 = y - outward;
        float x3 = x + size + outward;
        float y3 = y + size + outward;
        float x1 = x0 + t;
        float y1 = y0 + t;
        float x2 = x3 - t;
        float y2 = y3 - t;

        // Texture coordinates of the 9-slice lines.
        int slice = t * SLICE_SCALE;
        float texSize = 2f * slice + MID;
        float c1 = slice / texSize;
        float c2 = (slice + MID) / texSize;
        Matrix4f mat = gg.pose().last().pose();

        gg.flush();
        prepare(texture(theme, "square"));
        BufferBuilder buf = Tesselator.getInstance().begin(VertexFormat.Mode.QUADS, DefaultVertexFormat.POSITION_TEX);
        // Corners, then the four stretched edges.
        quad(buf, mat, x0, y0, x1, y1, 0f, 0f, c1, c1);
        quad(buf, mat, x2, y0, x3, y1, c2, 0f, 1f, c1);
        quad(buf, mat, x0, y2, x1, y3, 0f, c2, c1, 1f);
        quad(buf, mat, x2, y2, x3, y3, c2, c2, 1f, 1f);
        quad(buf, mat, x1, y0, x2, y1, c1, 0f, c2, c1);
        quad(buf, mat, x1, y2, x2, y3, c1, c2, c2, 1f);
        quad(buf, mat, x0, y1, x1, y2, 0f, c1, c1, c2);
        quad(buf, mat, x2, y1, x3, y2, c2, c1, 1f, c2);
        BufferUploader.drawWithShader(buf.buildOrThrow());
    }

    /** One textured rectangle, vertices in vanilla's GUI order (top-left first). */
    private static void quad(
            BufferBuilder buf,
            Matrix4f mat,
            float x0,
            float y0,
            float x1,
            float y1,
            float u0,
            float v0,
            float u1,
            float v1) {
        buf.addVertex(mat, x0, y0, 0f).setUv(u0, v0);
        buf.addVertex(mat, x0, y1, 0f).setUv(u0, v1);
        buf.addVertex(mat, x1, y1, 0f).setUv(u1, v1);
        buf.addVertex(mat, x1, y0, 0f).setUv(u1, v0);
    }

    /**
     * GL state of a frame draw: the textures are authored for bilinear
     * sampling (LINEAR filter, no mipmaps), whatever the filter a previous
     * resource reload left on them.
     */
    private static void prepare(ResourceLocation texture) {
        Minecraft.getInstance().getTextureManager().getTexture(texture).setFilter(true, false);
        RenderSystem.setShader(GameRenderer::getPositionTexShader);
        RenderSystem.setShaderTexture(0, texture);
        RenderSystem.setShaderColor(1f, 1f, 1f, 1f);
        RenderSystem.enableBlend();
        RenderSystem.defaultBlendFunc();
    }
}
